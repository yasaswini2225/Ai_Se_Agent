async def call_gemini(messages: List[Dict[str, str]], system_instruction: str) -> str:
    api_key = CURRENT_SETTINGS.gemini_api_key
    model = CURRENT_SETTINGS.model_name or "gemini-2.5-flash"
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"
    
    contents = []
    for m in messages:
        role = "user" if m.get("role") in ("user", "system") else "model"
        contents.append({"role": role, "parts": [{"text": m.get("content", "")}]})
    
    payload = {
        "contents": contents,
        "systemInstruction": {"parts": [{"text": system_instruction}]},
        "generationConfig": {
            "temperature": 0.3,
            "maxOutputTokens": 8192
        }
    }
    
    async with httpx.AsyncClient(timeout=45.0) as client:
        res = await client.post(url, json=payload)
        res.raise_for_status()
        data = res.json()
        candidates = data.get("candidates", [])
        if candidates and "content" in candidates[0]:
            parts = candidates[0]["content"].get("parts", [])
            return "".join([p.get("text", "") for p in parts])
        return "No response generated by Gemini."

async def call_openai_compatible(base_url: str, api_key: str, model: str, messages: List[Dict[str, str]], system_instruction: str) -> str:
    url = f"{base_url.rstrip('/')}/chat/completions"
    headers = {"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"}
    
    formatted_msgs = [{"role": "system", "content": system_instruction}] + [
        {"role": m["role"], "content": m["content"]} for m in messages
    ]
    
    payload = {
        "model": model,
        "messages": formatted_msgs,
        "temperature": 0.3
    }
    
    async with httpx.AsyncClient(timeout=45.0) as client:
        res = await client.post(url, headers=headers, json=payload)
        res.raise_for_status()
        data = res.json()
        return data["choices"][0]["message"]["content"]

async def call_ollama(base_url: str, model: str, messages: List[Dict[str, str]], system_instruction: str) -> str:
    url = f"{base_url.rstrip('/')}/api/chat"
    formatted_msgs = [{"role": "system", "content": system_instruction}] + messages
    payload = {"model": model, "messages": formatted_msgs, "stream": False}
    
    async with httpx.AsyncClient(timeout=60.0) as client:
        res = await client.post(url, json=payload)
        res.raise_for_status()
        data = res.json()
        return data.get("message", {}).get("content", "")

