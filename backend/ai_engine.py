async def run_autonomous_agent(task_prompt: str, context_files: Optional[List[str]] = None) -> Dict[str, Any]:
    """
    Takes a task, formulates a multi-step plan, creates/modifies files in the workspace,
    and returns the plan execution progress and generated artifacts.
    """
    provider = CURRENT_SETTINGS.provider
    has_api_key = bool(
        (provider == "gemini" and CURRENT_SETTINGS.gemini_api_key) or
        (provider == "openai" and CURRENT_SETTINGS.openai_api_key) or
        (provider == "groq" and CURRENT_SETTINGS.groq_api_key)
    )
    
    if has_api_key:
        workspace_tree = list_workspace_tree()
        tree_summary = json.dumps([f"{item['type']}: {item['name']}" for item in workspace_tree])
        agent_msg = f"""User Task: {task_prompt}
Current workspace files: {tree_summary}

Please generate the complete solution files to fulfill this task. Return ONLY valid JSON following the schema specified."""
        
        try:
            raw_response = await call_llm(
                messages=[{"role": "user", "content": agent_msg}],
                system_instruction=AGENT_PLANNER_SYSTEM_PROMPT
            )
            
            cleaned = re.sub(r"^```json\s*", "", raw_response.strip(), flags=re.MULTILINE)
            cleaned = re.sub(r"```$", "", cleaned.strip(), flags=re.MULTILINE)
            
            plan_data = json.loads(cleaned)
            
            written_files = []
            for file_entry in plan_data.get("files", []):
                p = file_entry.get("path")
                c = file_entry.get("content")
                if p and c:
                    write_workspace_file(p, c)
                    written_files.append(p)
                    
            plan_data["executed_files"] = written_files
            return plan_data
        except Exception:
            pass

    # High-quality smart native task generator
    return generate_native_agent_task(task_prompt)

