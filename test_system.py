import asyncio
from backend.main import app
from backend.workspace_manager import list_workspace_tree, read_workspace_file
from backend.execution_engine import execute_code
from backend.ai_engine import debug_code_error, run_autonomous_agent, fallback_chat

def run_tests():
    print("1. Checking workspace tree...")
    tree = list_workspace_tree()
    print(f"   Workspace items count: {len(tree)}")
    assert len(tree) > 0, "Tree is empty"

    print("2. Executing analytics.py...")
    code = read_workspace_file('analytics.py')['content']
    res = execute_code(code, 'python', 'analytics.py')
    print(f"   Status: {res['status']}, Elapsed: {res['execution_time_ms']}ms, Stdout length: {len(res['stdout'])}")
    assert res['status'] == 'success', "analytics.py execution failed"

    print("3. Executing buggy_sample.py...")
    buggy_sample_original = '''def process_user_records(records):
    total_score = 0
    for user in records:
        print(f"Processing {user['name']}...")
        total_score += user["score"]
    return total_score / len(records)
users = [{"name": "Alice", "score": 95}, {"name": "Charlie"}]
print(process_user_records(users))
'''
    from backend.workspace_manager import write_workspace_file
    write_workspace_file('buggy_sample.py', buggy_sample_original)
    buggy = buggy_sample_original
    buggy_res = execute_code(buggy, 'python', 'buggy_sample.py')
    print(f"   Status: {buggy_res['status']}, Stderr: {buggy_res['stderr'].splitlines()[-1] if buggy_res['stderr'] else 'None'}")
    assert buggy_res['status'] == 'error', "buggy_sample.py did not report error"

    print("4. Running AI Debugger on error...")
    debug_res = asyncio.run(debug_code_error('buggy_sample.py', buggy, buggy_res['stderr']))
    print(f"   Root cause: {debug_res['root_cause']}")
    assert debug_res.get('fixed_code'), "No fixed_code produced"

    print("5. Testing AI fixed code execution...")
    fixed_res = execute_code(debug_res['fixed_code'], 'python', 'buggy_sample.py')
    print(f"   Fixed status: {fixed_res['status']}, stdout: {fixed_res['stdout'].strip()[:60]}...")
    assert fixed_res['status'] == 'success', "Fixed code failed execution"

    print("6. Running AI Agent on task...")
    agent_res = asyncio.run(run_autonomous_agent('Build a scientific calculator with modern UI'))
    print(f"   Agent Summary: {agent_res['summary']}")
    print(f"   Files generated: {agent_res['executed_files']}")
    assert len(agent_res['executed_files']) > 0, "No files generated by agent"

    print("7. Testing AI Chat Q&A...")
    chat_reply = fallback_chat("Explain async event loops in Python")
    print(f"   Chat response length: {len(chat_reply)}")
    assert len(chat_reply) > 50, "Chat reply too short"

    print("\n=========================================")
    print("SUCCESS: ALL 7 SYSTEM TESTS PASSED PERFECTLY!")
    print("=========================================")

if __name__ == "__main__":
    run_tests()
